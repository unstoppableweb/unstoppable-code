#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { WEB_THEME_IDS, checkWebThemeUsage } from './check-web-theme-usage.mjs';
import { generateThemeFromRecipe } from './theme-generator.mjs';
import {
  buildCanonicalSemanticCssDeclarations,
  buildPrimitiveCssDeclarations,
} from './token-graph.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const recipePath = resolve(
  root,
  'packages/ui-shared/src/styles/theme-recipes.json',
);
const outputPath = resolve(
  root,
  'packages/ui-shared/src/styles/generated-theme-tokens.css',
);
const webOutputPath = resolve(
  root,
  'packages/ui-shared/src/styles/generated-theme-tokens.web.css',
);
const visualOutputPath = resolve(
  root,
  'packages/ui-shared/src/lib/agent-visual-theme-defaults.ts',
);
const visualHtmlPath = resolve(
  root,
  'packages/ui-shared/src/lib/agent-visual-html.ts',
);
const canopyTokensPath = resolve(
  root,
  'packages/ui-shared/src/styles/canopy-tokens-core.css',
);
const brandsPath = resolve(root, 'brands');

function declarations(source) {
  return Object.fromEntries(
    [...source.matchAll(/\s(--[\w-]+):\s*([^;]+);/g)].map((match) => [
      match[1],
      match[2].trim().replace(/\s+/g, ' '),
    ]),
  );
}

/** Brand packs override the default recipe; named themes remain shared. */
export function renderAgentVisualThemeDefaults(recipes) {
  const htmlSource = readFileSync(visualHtmlPath, 'utf8');
  const namesSource = htmlSource.match(
    /export const AGENT_VISUAL_THEME_VARIABLES = \[([\s\S]*?)\] as const/,
  );
  if (!namesSource) throw new Error('Visual theme variable list not found');
  const names = [...namesSource[1].matchAll(/'(--[^']+)'/g)].map(
    (match) => match[1],
  );
  const base = declarations(readFileSync(canopyTokensPath, 'utf8'));
  // These font hooks depend on host app font registration, which does not
  // exist in the isolated preview. Resolve to the same fallback stacks.
  base['--font-sans'] = base['--font-sans'].replace(
    "var(--font-inter, 'Inter')",
    "'Inter'",
  );
  base['--font-mono'] = base['--font-mono'].replace(
    "var(--font-jetbrains-mono, 'JetBrains Mono')",
    "'JetBrains Mono'",
  );
  const table = {};
  // Directory order differs by filesystem; the table must not.
  for (const brandId of readdirSync(brandsPath).sort()) {
    let brand;
    try {
      brand = JSON.parse(
        readFileSync(resolve(brandsPath, brandId, 'brand.json'), 'utf8'),
      );
    } catch {
      continue;
    }
    table[brandId] = {};
    for (const [name, sharedRecipe] of Object.entries(recipes)) {
      const recipe =
        name === 'default' ? brand.theme.default.recipe : sharedRecipe;
      const theme = generateThemeFromRecipe(
        recipe,
        `brand "${brandId}" theme "${name}"`,
      );
      table[brandId][name] = {};
      for (const appearance of ['light', 'dark']) {
        const mode = theme[appearance];
        const css = declarations(block(':root', mode, appearance === 'dark'));
        const values = { ...base, ...css };
        const resolveValue = (key, visited = new Set()) => {
          if (visited.has(key) || !values[key])
            throw new Error(`Unresolved theme token ${key}`);
          visited.add(key);
          return values[key].replace(/var\((--[\w-]+)\)/g, (_, target) =>
            resolveValue(target, new Set(visited)),
          );
        };
        table[brandId][name][appearance] = Object.fromEntries(
          names.map((key) => [key, resolveValue(key)]),
        );
      }
    }
  }
  return `/* GENERATED by scripts/brand/generate-theme-tokens.mjs. Do not edit.\n * Each brand's default recipe overrides the shared default; named themes are shared. */\nimport type { AgentVisualTheme } from './agent-visual-html';\n\nexport const AGENT_VISUAL_THEME_DEFAULTS: Readonly<Record<string, Readonly<Record<${Object.keys(
    recipes,
  )
    .map((name) => `'${name}'`)
    .join(
      ' | ',
    )}, Readonly<Record<'light' | 'dark', AgentVisualTheme['variables']>>>>>> = ${JSON.stringify(table, null, 2)};\n`;
}

function selectorFor(themeId, dark = false) {
  if (themeId === 'default') return dark ? ':root.dark' : ':root';
  return dark ? `[data-theme='${themeId}'].dark` : `[data-theme='${themeId}']`;
}

function sidebarForegroundDeclarations(dark) {
  const channel = dark ? '255 255 255' : '0 0 0';
  return [
    `  --sidebar-fg-primary: rgb(${channel});`,
    `  --sidebar-fg-secondary: rgb(${channel} / 72%);`,
    `  --sidebar-fg-tertiary: rgb(${channel} / 58%);`,
    `  --sidebar-fg-quaternary: rgb(${channel} / 36%);`,
  ].join('\n');
}

function block(selector, mode, dark) {
  return `${selector} {\n${buildPrimitiveCssDeclarations(mode.primitives)}\n${buildCanonicalSemanticCssDeclarations(mode.cssBindings)}\n${sidebarForegroundDeclarations(dark)}\n  --radius: ${mode.radius};\n}`;
}

function p3Block(selector, mode) {
  return `  ${selector} {\n${buildPrimitiveCssDeclarations(mode.primitives, 'displayP3', '    ')}\n${buildCanonicalSemanticCssDeclarations(mode.displayP3CssBindings, '    ')}\n  }`;
}

export function renderThemeTokens(
  recipes,
  { themeIds = Object.keys(recipes) } = {},
) {
  for (const id of themeIds) {
    if (!Object.hasOwn(recipes, id))
      throw new Error(`Unknown web theme: ${id}`);
  }
  const generated = Object.entries(recipes)
    .filter(([id]) => themeIds.includes(id))
    .map(([id, recipe]) => [
      id,
      generateThemeFromRecipe(recipe, `built-in theme "${id}"`),
    ]);
  const srgb = generated.flatMap(([id, theme]) => [
    block(selectorFor(id), theme.light, false),
    block(selectorFor(id, true), theme.dark, true),
  ]);
  const p3 = generated.flatMap(([id, theme]) => [
    p3Block(selectorFor(id), theme.light),
    p3Block(selectorFor(id, true), theme.dark),
  ]);

  return `/* GENERATED by scripts/brand/generate-theme-tokens.mjs.
 * Edit theme-recipes.json, then run pnpm run brand:theme-tokens. */

${srgb.join('\n\n')}

@supports (color: color(display-p3 1 1 1)) {
${p3.join('\n\n')}
}
`;
}

async function main() {
  if (!process.argv.includes('--visual-only')) checkWebThemeUsage();
  const recipes = JSON.parse(readFileSync(recipePath, 'utf8'));
  const rendered = renderThemeTokens(recipes);
  const webRendered = renderThemeTokens(recipes, { themeIds: WEB_THEME_IDS });
  const visualRendered = await prettier.format(
    renderAgentVisualThemeDefaults(recipes),
    {
      parser: 'typescript',
      singleQuote: true,
      trailingComma: 'all',
    },
  );
  if (process.argv.includes('--check')) {
    const stale = [
      [outputPath, rendered],
      [webOutputPath, webRendered],
      [visualOutputPath, visualRendered],
    ].filter(
      ([file, expected]) =>
        !existsSync(file) || readFileSync(file, 'utf8') !== expected,
    );
    if (stale.length) {
      throw new Error(
        `${stale.map(([file]) => file).join(', ')} is stale. Run pnpm run brand:theme-tokens and commit the result.`,
      );
    }
    process.stdout.write(
      'Generated full/web theme CSS and visual defaults are current.\n',
    );
    return;
  }
  if (!process.argv.includes('--visual-only')) {
    writeFileSync(outputPath, rendered);
    writeFileSync(webOutputPath, webRendered);
  }
  writeFileSync(visualOutputPath, visualRendered);
  process.stdout.write(
    `Generated ${Object.keys(recipes).length} themes${process.argv.includes('--visual-only') ? ` at ${visualOutputPath}` : ` at ${outputPath}, ${webOutputPath} and ${visualOutputPath}`}\n`,
  );
}

if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1])
) {
  await main();
}
